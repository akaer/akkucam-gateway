#!/usr/bin/env sh
set -eu

IMAGE="${GO_TEST_IMAGE:-golang:1.27.4-bookworm}"

docker run --rm -v "$PWD:/src" -w /src "$IMAGE" go vet ./...
docker run --rm -v "$PWD:/src" -w /src "$IMAGE" go test -count=1 ./...
docker run --rm -v "$PWD:/src" -w /src "$IMAGE" go test -race -count=1 ./...
docker build --build-arg COMMIT="$(git rev-parse HEAD 2>/dev/null || true)" -t akkucam-gateway:test .
